class Solution {
    public int maxSubArray(int[] nums) {
        int currSum = nums[0];
        int maxSum = nums[0];

        for (int i = 1; i < nums.length; i++) {
            int curr = nums[i];
            currSum = Math.max(curr, currSum + curr);
            maxSum = Math.max(maxSum, currSum);
        }

        return maxSum;
    }
}

